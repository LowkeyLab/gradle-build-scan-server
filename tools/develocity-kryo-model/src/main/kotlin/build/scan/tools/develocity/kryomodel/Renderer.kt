package build.scan.tools.develocity.kryomodel

import arrow.core.raise.Raise

private const val GENERATED_PACKAGE = "build.scan.tools.develocity.kryomodel.generated.v4_4_2"

fun Raise<GenerationError>.renderKotlinSources(wireClasses: List<WireClass>): Map<String, String> {
    if (GENERATED_PACKAGE.isBlank()) raise(GenerationError.EmptyPackage("generated package must not be blank"))
    val sorted = wireClasses.sortedBy { it.internalName }
    return mapOf(generatedRelativePath() to renderDescriptorCatalog(sorted))
}

fun generatedRelativePath(): String =
    GENERATED_PACKAGE.replace('.', '/') + "/Develocity442WireModel.kt"

private fun Raise<GenerationError>.renderDescriptorCatalog(wireClasses: List<WireClass>): String = buildString {
    appendLine("package $GENERATED_PACKAGE")
    appendLine()
    appendLine("// Generated by tools/develocity-kryo-model from Develocity Gradle plugin 4.4.2 bytecode.")
    appendLine("// Neutral wire metadata only; this file does not contain decompiled Develocity implementations.")
    appendLine("public data class GeneratedWireField(")
    appendLine("    public val name: String,")
    appendLine("    public val descriptor: String,")
    appendLine("    public val typeName: String,")
    appendLine(")")
    appendLine()
    appendLine("public data class GeneratedWireClass(")
    appendLine("    public val binaryName: String,")
    appendLine("    public val serializerNames: List<String>,")
    appendLine("    public val fields: List<GeneratedWireField>,")
    appendLine(")")
    appendLine()
    appendLine("public object Develocity442WireModel {")
    appendLine("    public const val pluginVersion: String = \"4.4.2\"")
    appendLine("    public val classes: List<GeneratedWireClass> = listOf(")
    wireClasses.forEachIndexed { index, wireClass ->
        append(renderWireClass(wireClass).prependIndent("        "))
        if (index != wireClasses.lastIndex) appendLine(",") else appendLine()
    }
    appendLine("    )")
    appendLine("}")
}

private fun Raise<GenerationError>.renderWireClass(wireClass: WireClass): String = buildString {
    if (wireClass.internalName.isBlank() || wireClass.binaryName.isBlank()) raise(GenerationError.InvalidClassName(wireClass.internalName))
    appendLine("GeneratedWireClass(")
    appendLine("    binaryName = \"${wireClass.binaryName.escapeKotlin()}\",")
    appendLine("    serializerNames = listOf(")
    wireClass.serializerBindings.map { it.serializerInternalName.toBinaryName() }.distinct().sorted().forEachIndexed { index, serializerName ->
        val suffix = if (index == wireClass.serializerBindings.map { it.serializerInternalName }.distinct().lastIndex) "" else ","
        appendLine("        \"${serializerName.escapeKotlin()}\"$suffix")
    }
    appendLine("    ),")
    appendLine("    fields = listOf(")
    wireClass.fields.forEachIndexed { index, field ->
        val suffix = if (index == wireClass.fields.lastIndex) "" else ","
        appendLine("        GeneratedWireField(\"${field.name.escapeKotlin()}\", \"${field.descriptor.escapeKotlin()}\", \"${field.typeName.escapeKotlin()}\")$suffix")
    }
    appendLine("    ),")
    append(")")
}

private fun String.escapeKotlin(): String =
    replace("\\", "\\\\").replace("\"", "\\\"")
